from io import BytesIO

from PIL import Image, ImageDraw, ImageFont

from .analysis import FEATURE_LABELS


class ReportLayout:
    page_width = 1275
    page_height = 1650
    margin = 75
    content_width = page_width - 2 * margin
    content_bottom = page_height - 110

    def __init__(self) -> None:
        self.pages: list[Image.Image] = []
        self.body_font = ReportLayout._font(22)
        self.new_page()

    def new_page(self) -> None:
        self.page = Image.new("RGB", (self.page_width, self.page_height), "white")
        self.pages.append(self.page)
        self.draw = ImageDraw.Draw(self.page)
        self.y = self.margin

    def ensure_space(self, height: int) -> None:
        if self.y + height > self.content_bottom:
            self.new_page()

    def draw_heading(self, text: str, size: int, spacing: int) -> None:
        self.ensure_space(spacing)
        self.draw.text((self.margin, self.y), text, fill="black", font=ReportLayout._font(size))
        self.y += spacing

    def draw_image(self, data: bytes) -> None:
        with Image.open(BytesIO(data)) as source:
            image = source.convert("RGB")
        max_image_height = 780
        scale = min(self.content_width / image.width, max_image_height / image.height, 1.0)
        display = image.resize((max(1, int(image.width * scale)), max(1, int(image.height * scale))))
        self.ensure_space(display.height)
        self.page.paste(display, (self.margin, self.y))
        self.y += display.height + 35

    def draw_paragraph(self, text: str) -> None:
        line_height = int(self.draw.textbbox((0, 0), "Ag", font=self.body_font)[3] * 1.45)
        for line in ReportLayout._wrapped_lines(self.draw, text, self.content_width, self.body_font):
            self.ensure_space(line_height)
            self.draw.text((self.margin, self.y), line, fill="black", font=self.body_font)
            self.y += line_height
        self.y += 15

    def to_pdf(self) -> bytes:
        small_font = ReportLayout._font(18)
        for page in self.pages:
            ImageDraw.Draw(page).text(
                (self.margin, self.page_height - 70),
                "Generated by MRXS Analysis Workbench",
                fill="black",
                font=small_font,
            )

        output = BytesIO()
        self.pages[0].save(output, format="PDF", resolution=150.0, save_all=True, append_images=self.pages[1:])
        return output.getvalue()

    @staticmethod
    def _font(size: int):
        try:
            return ImageFont.truetype("DejaVuSans.ttf", size)
        except OSError:
            return ImageFont.load_default()

    @staticmethod
    def _wrapped_lines(draw: ImageDraw.ImageDraw, text: str, width: int, font) -> list[str]:
        """Add words to the last line until its rendered width exceeds the limit."""
        lines: list[str] = []
        for word in text.split():
            candidate = f"{lines[-1]} {word}" if lines else word
            if not lines or draw.textbbox((0, 0), candidate, font=font)[2] > width:
                lines.append(word)
            else:
                lines[-1] = candidate
        return lines


def build_report_pdf(image_bytes: list[bytes], report: dict) -> bytes:
    if not image_bytes:
        raise ValueError("At least one image is required to build a report")

    layout = ReportLayout()
    layout.draw_heading("MRXS Vision Analysis Report", size=42, spacing=70)
    layout.draw_heading("Selected images", size=25, spacing=45)
    for data in image_bytes:
        layout.draw_image(data)

    layout.ensure_space(80)
    layout.draw_heading("Analysis", size=25, spacing=40)

    aggregate = report.get("aggregate", {})
    layout.draw_paragraph(
        f"Completed {aggregate.get('analyses_completed', 0)} of "
        f"{aggregate.get('analyses_requested', 0)} requested analyses."
    )

    model_results = report.get("model_results", [])
    if not model_results:
        layout.draw_paragraph("No model returned a valid analysis.")

    for result in model_results:
        image_number = result.get("image_index", 0) + 1
        layout.draw_heading(
            f"Image {image_number} - {result.get('model', 'Unknown model')}",
            size=25,
            spacing=45,
        )
        layout.draw_paragraph(result.get("highlights", "No highlights available."))
        layout.draw_paragraph(
            f"Glands: {result.get('glands_score', 'not available')} | "
            f"Stroma: {result.get('stroma_score', 'not available')} | "
            f"Total: {result.get('total_score', 'not available')} | "
            f"Category: {result.get('final_prediction_category', 'Unclear')} | "
            f"Confidence: {result.get('confidence', 'Low')}"
        )

        feature_scores = result.get("feature_scores", {})
        if feature_scores:
            layout.draw_heading("Feature scores", size=22, spacing=38)
            for feature, data in feature_scores.items():
                layout.draw_paragraph(
                    f"- {FEATURE_LABELS.get(feature, feature)}: {data.get('score', 'not available')} "
                    f"({data.get('confidence', 'Low')}) - {data.get('rationale', '')}"
                )

    errors = report.get("errors", [])
    if errors:
        layout.draw_heading("Analysis errors", size=25, spacing=45)
        for error in errors:
            layout.draw_paragraph(
                f"- Image {error.get('image_index', 0) + 1}, "
                f"{error.get('model', 'unknown model')}: {error.get('error', 'Unknown error')}"
            )

    return layout.to_pdf()
